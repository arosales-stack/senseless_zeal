// Worker entry: serves the static site and a page per work. Orders go from the page to FormSubmit.
// - /<work-id>          → the home page, with that work's title and image in the link preview;
//                         the page script then opens the work in the viewer
// - anything else       → static files from public/, or back to the home page
import WORKS from "./works.json";   // generated by tools/build.py

const BY_ID = new Map(WORKS.map(w => [w.id, w]));
// Old links keep working after a work is renamed.
const RENAMED = { paris: "city-life" };

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    const id = url.pathname.replace(/^\/+|\/+$/g, "");
    if (RENAMED[id]) return Response.redirect(`${url.origin}/${RENAMED[id]}${url.search}`, 301);
    const work = BY_ID.get(id);
    if (work) return workPage(work, url, env);

    // Not a file and not a work: send people to the home page rather than an error.
    if (request.method === "GET") return Response.redirect(url.origin + "/", 302);
    return env.ASSETS.fetch(request);
  },
};

async function workPage(w, url, env) {
  const home = await env.ASSETS.fetch(new Request(url.origin + "/", { method: "GET" }));
  const title = `${w.title} — Senseless Zeal`;
  const desc = `${w.medium}. Hand-drawn by Senseless Zeal. Prints to order.`;
  const image = `${url.origin}/img/${w.id}.webp`;
  const set = (attr, value) => ({ element(el) { el.setAttribute(attr, value); } });
  return new HTMLRewriter()
    .on("title", { element(el) { el.setInnerContent(title); } })
    .on('meta[name="description"]', set("content", desc))
    .on('meta[property="og:title"]', set("content", title))
    .on('meta[property="og:description"]', set("content", desc))
    .on('meta[property="og:image"]', set("content", image))
    .on('meta[property="og:url"]', set("content", `${url.origin}/${w.id}`))
    .on("head", { element(el) {
      el.append(`<meta property="og:image:width" content="${w.w}"><meta property="og:image:height" content="${w.h}"><link rel="canonical" href="${url.origin}/${w.id}">`, { html: true });
    } })
    .transform(home);
}
