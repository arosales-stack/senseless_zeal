/* Senseless Zeal: page behaviour
   1. Data & helpers   2. Theme   3. Wall & filters   4. Viewer   5. Order form   6. Shared links
   Works and tags come from js/works.js, generated by tools/build.py from works.json. */
(() => {
"use strict";

/* 1. Data & helpers --------------------------------------------------------- */
const WORKS = window.WORKS || [];
const TAGS  = window.TAGS  || [];
// Prices: keep identical to PRICES in functions/api/order.js
const SIZES = [
  {id:"A4", label:"A4 · 21 × 29.7 cm",   price:35},
  {id:"A3", label:"A3 · 29.7 × 42 cm",   price:55},
  {id:"A2", label:"A2 · 42 × 59.4 cm",   price:90},
];
// Orders go straight to FormSubmit. The code below is FormSubmit's alias for the inbox:
// it delivers to you without your email address ever appearing in the page.
const ORDER_ENDPOINT = "https://formsubmit.co/ajax/0518167f9410fac0f6a6d632b3ea176a";
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

const $   = s => document.querySelector(s);
const eur = n => "€" + n;

// Discourage casual saving: no right-click menu or dragging on artwork and photos.
document.addEventListener("contextmenu", e => { if(e.target.closest(".protect")) e.preventDefault(); });
document.addEventListener("dragstart",   e => { if(e.target.closest(".protect")) e.preventDefault(); });

/* 2. Theme ------------------------------------------------------------------ */
// Every visit opens in light mode. The switch changes it for this visit only; nothing is remembered.
const root = document.documentElement;
const themeBtn = $("#theme");
const isDark = () => root.dataset.theme === "dark";
const paintTheme = () => themeBtn.setAttribute("aria-checked", String(isDark()));
themeBtn.addEventListener("click", () => {
  root.dataset.theme = isDark() ? "light" : "dark";
  paintTheme();
});
paintTheme();

/* 3. Wall & filters --------------------------------------------------------- */
const wall    = $("#wall");
const filters = $("#filters");
let visible   = WORKS.map((_, i) => i);   // works shown under the active filter (the viewer cycles through these)
let activeTag = "";
let lastCols  = 0;

const pieces = WORKS.map((w, i) => {
  const b = document.createElement("button");
  b.type = "button";
  b.className = "piece tone-" + w.tone;
  b.innerHTML = `<img class="protect" src="img/${w.id}-sm.webp" width="${w.w}" height="${w.h}" loading="${i < 6 ? "eager" : "lazy"}" decoding="async" alt=""><span class="cap"><b></b></span>`;
  b.querySelector("img").alt = `${w.title}, drawing by Senseless Zeal`;
  b.querySelector("b").textContent = w.title;
  b.addEventListener("click", () => openViewer(i));
  return b;
});

// Masonry that reads left to right: each work goes into the shortest column,
// so the order in works.json is the order you see across the top rows.
function layout(force){
  const gap = parseFloat(getComputedStyle(wall).columnGap) || 24;
  const n = Math.max(1, Math.min(3, Math.floor((wall.clientWidth + gap) / (300 + gap))));
  if(n === lastCols && !force) return;
  lastCols = n;
  const cols = Array.from({length:n}, () => Object.assign(document.createElement("div"), {className:"col"}));
  const heights = new Array(n).fill(0);
  visible.forEach(i => {
    const k = heights.indexOf(Math.min(...heights));
    cols[k].appendChild(pieces[i]);
    heights[k] += WORKS[i].h / WORKS[i].w + 0.25;   // image ratio + caption and spacing
  });
  wall.replaceChildren(...cols);
}
let resizeTimer;
addEventListener("resize", () => { clearTimeout(resizeTimer); resizeTimer = setTimeout(() => layout(false), 120); });

function addTag(id, label, n){
  const b = document.createElement("button");
  b.type = "button";
  b.className = "tag";
  b.dataset.tag = id;
  b.innerHTML = `<i class="hole" aria-hidden="true"></i><span></span><small></small>`;
  b.querySelector("span").textContent = label;
  b.querySelector("small").textContent = n;
  b.addEventListener("click", () => setTag(id));
  filters.appendChild(b);
}
addTag("", "All", WORKS.length);
// tags listed by how many works they hold, biggest first
TAGS.map(t => ({...t, n: WORKS.filter(w => w.tags.includes(t.id)).length}))
    .filter(t => t.n)
    .sort((a, b) => b.n - a.n)
    .forEach(t => addTag(t.id, t.label, t.n));

function setTag(id){
  activeTag = TAGS.some(t => t.id === id) ? id : "";
  visible = WORKS.flatMap((w, i) => (!activeTag || w.tags.includes(activeTag)) ? [i] : []);
  layout(true);
  filters.querySelectorAll(".tag").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.tag === activeTag)));
  const label = activeTag ? TAGS.find(t => t.id === activeTag).label : "";
  $("#count").textContent = `${visible.length} ${visible.length === 1 ? "work" : "works"}${label ? " in " + label : ""}`;
  try{   // keep the filter in the address so a filtered view can be shared
    const u = new URL(location.href);
    activeTag ? u.searchParams.set("tag", activeTag) : u.searchParams.delete("tag");
    history.replaceState(null, "", u);
  }catch(e){}
}
let startTag = "";
try{ startTag = new URL(location.href).searchParams.get("tag") || ""; }catch(e){}
setTag(startTag);

/* 4. Viewer ----------------------------------------------------------------- */
const viewer = $("#viewer");
const vImg = $("#vImg");
let cur = 0, lastFocus = null;

function show(i){
  cur = i;
  const w = WORKS[i];
  vImg.src = `img/${w.id}.webp`;
  vImg.className = "protect tone-" + w.tone;
  vImg.alt = `${w.title}, drawing by Senseless Zeal`;
  $("#vIndex").textContent = `${visible.indexOf(i) + 1} / ${visible.length}`;
  $("#vTitle").textContent = w.title;
  $("#vMedium").textContent = w.medium;
  $("#vFrom").textContent = `Prints from ${eur(SIZES[0].price)}. Originals on request.`;
}
// step through the works currently visible under the active filter
function step(d){
  const k = visible.indexOf(cur);
  show(visible[(k + d + visible.length) % visible.length]);
  try{ history.replaceState({work:WORKS[cur].id}, "", BASE + WORKS[cur].id + location.search); }catch(e){}
  document.title = `${WORKS[cur].title} — Senseless Zeal`;
}
// Each work has its own address (senselesszeal.com/<id>) so it can be sent as a link.
const BASE = new URL(".", location.href).pathname;            // "/" on the live site
const workUrl = id => location.origin + BASE + (id || "") + location.search;
function setAddress(id){
  try{
    const target = BASE + (id || "") + location.search;
    if(location.pathname + location.search !== target) history.pushState({work:id || null}, "", target);
  }catch(e){}
  document.title = id ? `${WORKS.find(w => w.id === id).title} — Senseless Zeal` : HOME_TITLE;
}
const HOME_TITLE = document.title.replace(/^.* — Senseless Zeal$/, "Senseless Zeal — Drawings");

function openViewer(i, {updateAddress = true} = {}){
  if(!visible.includes(i)) setTag("");                     // a shared work that's hidden by a filter
  lastFocus = document.activeElement;
  show(i);
  viewer.hidden = false;
  document.body.style.overflow = "hidden";
  if(updateAddress) setAddress(WORKS[i].id);
  $("#vClose").focus({preventScroll:true});
}
function closeViewer(restoreFocus = true, {updateAddress = true} = {}){
  if(viewer.hidden) return;
  viewer.hidden = true;
  document.body.style.overflow = "";
  if(updateAddress) setAddress("");
  if(restoreFocus && lastFocus) lastFocus.focus({preventScroll:true});
}
$("#vPrev").addEventListener("click", () => step(-1));
$("#vNext").addEventListener("click", () => step(1));
$("#vClose").addEventListener("click", () => closeViewer());
vImg.addEventListener("click", () => closeViewer());
// "Order this print": pick the work in the form, then land on the form in one instant jump.
// No smooth scroll across the whole page, and no auto-focus on touch screens: opening the
// keyboard mid-scroll is what made phones land in the wrong place.
$("#vOrder").addEventListener("click", () => {
  $("#piece").value = WORKS[cur].id;
  updateTotal();
  closeViewer(false);
  $("#order").scrollIntoView({behavior:"instant", block:"start"});
  if(matchMedia("(hover: hover) and (pointer: fine)").matches) $("#name").focus({preventScroll:true});
});
document.addEventListener("keydown", e => {
  if(viewer.hidden) return;
  if(e.key === "Escape") closeViewer();
  else if(e.key === "ArrowRight") step(1);
  else if(e.key === "ArrowLeft") step(-1);
  else if(e.key === "Tab"){   // keep keyboard focus inside the open viewer
    const f = [...viewer.querySelectorAll("button")];
    const first = f[0], last = f[f.length - 1];
    if(e.shiftKey && document.activeElement === first){ e.preventDefault(); last.focus(); }
    else if(!e.shiftKey && document.activeElement === last){ e.preventDefault(); first.focus(); }
  }
});
// Share: the phone's share sheet when there is one, otherwise copy the link.
const toast = $("#vToast");
function flash(msg){ toast.textContent = msg; toast.classList.add("on"); clearTimeout(flash.t); flash.t = setTimeout(() => toast.classList.remove("on"), 1800); }
$("#vShare").addEventListener("click", async () => {
  const w = WORKS[cur], url = workUrl(w.id);
  if(navigator.share){
    try{ await navigator.share({title:`${w.title} — Senseless Zeal`, url}); }catch(e){}
    return;
  }
  try{ await navigator.clipboard.writeText(url); flash("Link copied"); }
  catch(e){ flash(url); }
});

// Back/forward buttons open and close works like a normal page.
addEventListener("popstate", () => {
  const i = WORKS.findIndex(w => w.id === location.pathname.slice(BASE.length));
  if(i >= 0) openViewer(i, {updateAddress:false});
  else closeViewer(false, {updateAddress:false});
});

let touchX = null;
viewer.addEventListener("touchstart", e => { touchX = e.touches[0].clientX; }, {passive:true});
viewer.addEventListener("touchend", e => {
  if(touchX === null) return;
  const d = e.changedTouches[0].clientX - touchX;
  if(Math.abs(d) > 50) step(d < 0 ? 1 : -1);
  touchX = null;
});

/* 5. Order form ------------------------------------------------------------- */
const form = $("#form");
$("#prices").innerHTML = SIZES.map(s => `<div><span>${s.label}</span><span>${eur(s.price)}</span></div>`).join("");
$("#piece").innerHTML  = WORKS.map(w => `<option value="${w.id}"></option>`).join("");
[...$("#piece").options].forEach((o, i) => { o.textContent = WORKS[i].title; });
$("#sizes").innerHTML  = SIZES.map((s, i) => `<label><input type="radio" name="size" value="${s.id}"${i === 0 ? " checked" : ""}><span><b>${s.id}</b>${eur(s.price)}</span></label>`).join("");

function readOrder(){
  const size = SIZES.find(s => s.id === form.size.value) || SIZES[0];
  const qty  = Math.min(10, Math.max(1, parseInt(form.qty.value, 10) || 1));
  const w    = WORKS.find(x => x.id === form.piece.value) || WORKS[0];
  return {
    piece:w.id, title:w.title, size:size.id, unitPrice:size.price, qty, total:size.price * qty,
    name:form.name.value.trim(), email:form.email.value.trim(), country:form.country.value.trim(),
    note:form.note.value.trim(), original:form.original.checked,
  };
}
function updateTotal(){ $("#total").textContent = eur(readOrder().total); }
function stepQty(d){
  const q = form.qty;
  q.value = Math.min(10, Math.max(1, (parseInt(q.value, 10) || 1) + d));
  updateTotal();
}
$("#qtyDown").addEventListener("click", () => stepQty(-1));
$("#qtyUp").addEventListener("click", () => stepQty(1));
form.addEventListener("input", updateTotal);
updateTotal();

form.addEventListener("submit", async e => {
  e.preventDefault();
  const o = readOrder(), err = $("#err"), btn = $("#submit");
  const problem = !o.name ? "Add your name."
    : !EMAIL_RE.test(o.email) ? "Add a valid email so the payment link can reach you."
    : !o.country ? "Add the country the print ships to." : "";
  if(problem){ err.textContent = problem; err.hidden = false; return; }
  err.hidden = true;
  btn.disabled = true; btn.textContent = "Sending…";

  let sent = false;   // set once FormSubmit accepts the order
  try{
    const ref = "SZ-" + Date.now().toString(36).toUpperCase().slice(-6);
    const confirmation =
      `Thank you, ${o.name}.\n\nYour order ${ref}: ${o.qty} × ${o.title}, ${o.size} print — ${eur(o.total)}, shipping to ${o.country} included.\n\n` +
      `I'll send your secure payment link personally within 24 hours. Nothing is charged until you pay through it.\n\n` +
      (o.original ? `You mentioned interest in the original drawing. I'll write to you about it.\n\n` : "") +
      `Every work is drawn by hand. No AI.\nSenseless Zeal`;
    const r = await fetch(ORDER_ENDPOINT, {
      method:"POST",
      headers:{"Content-Type":"application/json", Accept:"application/json"},
      body:JSON.stringify({
        _subject:`New order ${ref}: ${o.qty} × ${o.title} ${o.size} (${eur(o.total)})${o.original ? " + original interest" : ""}`,
        _template:"table", _captcha:"false",
        _autoresponse:confirmation,                 // FormSubmit emails this to the buyer ("email" field)
        Reference:ref, Work:o.title, Size:o.size, Quantity:o.qty, Total:eur(o.total),
        Name:o.name, email:o.email, Country:o.country,
        "Interested in original":o.original ? "Yes" : "No", Note:o.note || "—",
      }),
    });
    const res = await r.json().catch(() => ({}));
    if(r.ok && String(res.success) !== "false") sent = true;
    else throw new Error("server");
  }catch(ex){
    err.textContent = "The order didn't go through. Check your connection and try again.";
    err.hidden = false; btn.disabled = false; btn.textContent = "Place order";
    return;
  }

  const box = $("#orderBox");
  box.innerHTML = `<div class="done" role="status"><h3>Thank you.</h3><p class="summary"></p>
    <p>Check your inbox for the confirmation email with the payment link. Your print goes into production once payment is complete.</p>
    <button class="btn ghost" type="button" id="again">Order another print</button></div>`;
  box.querySelector(".summary").textContent = `${o.qty} × ${o.title}, ${o.size} — ${eur(o.total)}.` + (sent ? ` Confirmation sent to ${o.email}.` : "");
  $("#again").addEventListener("click", () => location.reload());
});

/* 6. Shared links ------------------------------------------------------------ */
{
  const i = WORKS.findIndex(w => w.id === location.pathname.slice(BASE.length));
  if(i >= 0){ try{ history.replaceState({work:null}, "", BASE + location.search); }catch(e){} openViewer(i); }
}
})();
